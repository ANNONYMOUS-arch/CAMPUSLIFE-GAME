export function resolveMaxActiveNpcs(
  graphicsQuality: GraphicsQuality,
  isSoftwareGl: boolean
): number {
  if (isSoftwareGl) return 14;
  switch (graphicsQuality) {
    case 'low':
      return 12;
    case 'medium':
      return 16;
    case 'high':
    case 'auto':
    default:
      return 20;
  }
}

export function getStudentRosterForWorld(
  mode: 'exterior' | 'interior',
  buildingId: string | undefined,
  maxActiveNpcs: number
): StudentNpcProfile[] {
  const pool =
    mode === 'exterior'
      ? EXTERIOR_STUDENT_ROSTER
      : buildingId
        ? INTERIOR_STUDENT_ROSTERS[buildingId] ?? []
        : [];
  const cap = Math.max(0, Math.min(pool.length, maxActiveNpcs));
  return pool
    .slice()
    .sort((a, b) => a.priority - b.priority)
    .slice(0, cap);
}
