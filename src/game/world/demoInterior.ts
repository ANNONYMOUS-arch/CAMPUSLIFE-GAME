function makeBoxCollider(
  id: string,
  label: string,
  x: number,
  y: number,
  z: number,
  width: number,
  height: number,
  depth: number
): AabbCollider {
  return {
    id,
    label,
    minX: x - width / 2,
    maxX: x + width / 2,
    minY: y - height / 2,
    maxY: y + height / 2,
    minZ: z - depth / 2,
    maxZ: z + depth / 2,
  };
}

function buildStraightNorthStair(
  id: string,
  fromFloor: number,
  toFloor: number,
  centerX: number,
  width: number,
  startZ: number,
  stepCount: number,
  totalRise: number,
  totalRun: number
): InteriorStairSpec {
  const stepRise = totalRise / stepCount;
  const stepDepth = totalRun / stepCount;
  const steps: StepSurface[] = [];
  const treads: InteriorStairTreadVisual[] = [];

  for (let i = 0; i < stepCount; i++) {
    const elevation = Number(((i + 1) * stepRise).toFixed(3));
    const treadCenterZ = startZ - (i + 0.5) * stepDepth;
    steps.push({
      id: `${id}-step-${i}`,
      minX: centerX - width / 2,
      maxX: centerX + width / 2,
      minZ: treadCenterZ - stepDepth * 0.56,
      maxZ: treadCenterZ + stepDepth * 0.56,
      elevation,
    });
    treads.push({
      x: centerX,
      y: elevation - stepRise * 0.5,
      z: treadCenterZ,
      width,
      height: stepRise,
      depth: stepDepth + 0.02,
    });
  }

  const railings: InteriorSurfaceSpec[] = [
    {
      id: `${id}-west-balustrade`,
      role: 'railing',
      x: centerX - width / 2 - 0.06,
      y: totalRise + 0.52,
      z: startZ - totalRun / 2,
      width: 0.12,
      height: 1.04,
      depth: totalRun + 0.3,
      collides: true,
    },
    {
      id: `${id}-south-balustrade`,
      role: 'railing',
      x: centerX,
      y: totalRise + 0.52,
      z: startZ + 0.14,
      width: width + 0.2,
      height: 1.04,
      depth: 0.12,
      collides: true,
    },
  ];

  return {
    id,
    fromFloor,
    toFloor,
    steps,
    treads,
    railings,
  };
}

